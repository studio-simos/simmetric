/**
 * ocr-baseline — pre-fix OCR metric collection (Phase 205, OCR-05 feed / D-16).
 *
 * Generates 3 throwaway text-bearing SVG pages, rasterizes them via sharp,
 * and runs them through the REAL current (pre-fix) OCR posture:
 *   model glm-ocr:latest via client.chat, options
 *   { temperature: 0, num_predict: OCR_NUM_PREDICT (default 8192), num_ctx: 4096 }
 * WITHOUT OCR_NUM_CTX set and WITHOUT top_k — the production-default posture
 * that later plans change must be captured as it exists today (D-16).
 *
 * Gating: requires OLLAMA_BASE_URL set. When absent the script logs the
 * honest skip reason and exits 0 — never fake data.
 *
 * Results are appended into the marker-delimited baseline block of
 * docs/OCR_RELIABILITY.md (idempotent: reruns replace the block rows). If
 * Ollama is unreachable mid-run, the honest pending note is (re)written
 * instead of fabricated rows.
 *
 * Usage:
 *   OLLAMA_BASE_URL=http://localhost:11434 node scripts/ocr-baseline.cjs
 *
 * Dependency resolution: ollama AND sharp do NOT resolve from scripts/ under
 * the pnpm isolated layout — both resolve through the server package's
 * node_modules (same pattern as build-glm-ocr-optimized.cjs; importing
 * server dist is forbidden per 205-PATTERNS.md). All fallible work —
 * including the requires — lives inside main()'s try/catch: the script
 * never throws uncaught.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const TOOL = "[ocr-baseline]";

const REPO_ROOT = path.join(__dirname, "..");
const DOC_PATH = path.join(REPO_ROOT, "docs", "OCR_RELIABILITY.md");
const BLOCK_BEGIN = "<!-- baseline:begin (auto-generated by scripts/ocr-baseline.cjs — do not hand-edit rows) -->";
const BLOCK_END = "<!-- baseline:end -->";

// ---------------------------------------------------------------------------
// Fixture generation: throwaway text-bearing SVG pages rasterized by sharp
// (RESEARCH-probed: sharp rasterizes SVG including <text>).
// ---------------------------------------------------------------------------

function escapeXml(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function textSvg({ title, lines, fontSize, lineHeight, width, height }) {
  const body = lines
    .map(
      (line, i) =>
        `<text x='40' y='${60 + i * lineHeight}' font-size='${fontSize}' font-family='sans-serif' fill='black'>${escapeXml(line)}</text>`,
    )
    .join("\n");
  return Buffer.from(
    `<svg xmlns='http://www.w3.org/2000/svg' width='${width}' height='${height}'>` +
      `<rect width='${width}' height='${height}' fill='white'/>` +
      `<text x='40' y='40' font-size='${Math.round(fontSize * 1.3)}' font-family='sans-serif' font-weight='bold' fill='black'>${escapeXml(title)}</text>` +
      body +
      `</svg>`,
  );
}

function buildFixtures() {
  const lorem = [
    "The quick brown fox jumps over the lazy dog near the",
    "riverbank while the calm river reflects the evening sky.",
    "Reliable OCR pipelines need enough context window to fit",
    "the whole prompt, the image tokens and the expected output.",
    "Silent truncation loses page content at prompt composition.",
    "Deterministic sampling keeps repeated runs comparable.",
    "A measured baseline makes the fix provable, not hopeful.",
    "Documentation lives next to the runbook for operators.",
  ];
  return [
    {
      id: "baseline-straight-text",
      note: "plain text page, straight, moderate density",
      svg: textSvg({
        title: "OCR Baseline Fixture A",
        lines: lorem.slice(0, 5),
        fontSize: 22,
        lineHeight: 40,
        width: 640,
        height: 320,
      }),
    },
    {
      id: "baseline-dense-text",
      note: "dense text page (more lines, smaller font)",
      svg: textSvg({
        title: "OCR Baseline Fixture B",
        lines: [...lorem, ...lorem.map((l) => l.toLowerCase())],
        fontSize: 18,
        lineHeight: 30,
        width: 640,
        height: 560,
      }),
    },
    {
      id: "baseline-small-text",
      note: "small text page (challenging for VLM OCR)",
      svg: textSvg({
        title: "OCR Baseline Fixture C",
        lines: lorem.slice(0, 4),
        fontSize: 12,
        lineHeight: 20,
        width: 640,
        height: 200,
      }),
    },
  ];
}

// ---------------------------------------------------------------------------
// Docs table update (marker-delimited block — idempotent replace)
// ---------------------------------------------------------------------------

function readDoc() {
  try {
    return fs.readFileSync(DOC_PATH, "utf-8");
  } catch {
    return null;
  }
}

function writeBaselineBlock(content, blockContent) {
  const block = `${BLOCK_BEGIN}\n${blockContent}\n${BLOCK_END}`;
  if (content.includes(BLOCK_BEGIN) && content.includes(BLOCK_END)) {
    const start = content.indexOf(BLOCK_BEGIN);
    const end = content.indexOf(BLOCK_END) + BLOCK_END.length;
    return content.slice(0, start) + block + content.slice(end);
  }
  // No block yet: append at end of file.
  const sep = content.endsWith("\n") ? "" : "\n";
  return `${content}${sep}\n${block}\n`;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  try {
    if (!process.env.OLLAMA_BASE_URL) {
      // Honest gate: no daemon target → skip with reason, exit 0 (never fake).
      const note =
        `${TOOL} skipped: OLLAMA_BASE_URL is not set — no baseline collected (honest pending note written to docs/OCR_RELIABILITY.md).\n` +
        `${TOOL} to collect: OLLAMA_BASE_URL=http://localhost:11434 node scripts/ocr-baseline.cjs (requires glm-ocr:latest pulled on the daemon).`;
      console.log(note);
      const doc = readDoc();
      if (doc) {
        const pending =
          `**Baseline status: PENDING** — no Ollama daemon was reachable when\n` +
          `scripts/ocr-baseline.cjs last ran (\`OLLAMA_BASE_URL\` unset). The rows\n` +
          `below are placeholders until an operator run fills them in; never\n` +
          `hand-write numbers here.\n\n` +
          `Collect with: \`OLLAMA_BASE_URL=http://localhost:11434 node scripts/ocr-baseline.cjs\`\n` +
          `(requires \`ollama pull glm-ocr:latest\` on the daemon).`;
        const updated = writeBaselineBlock(doc, pending);
        fs.writeFileSync(DOC_PATH, updated);
        console.log(`${TOOL} pending note written to docs/OCR_RELIABILITY.md`);
      } else {
        console.log(`${TOOL} docs/OCR_RELIABILITY.md not found — nothing to update`);
      }
      return;
    }

    // Resolve deps through the server package (pnpm isolated layout —
    // neither ollama nor sharp resolves from scripts/).
    const depPaths = [path.join(REPO_ROOT, "packages", "server")];
    const ollamaMod = require(require.resolve("ollama", { paths: depPaths }));
    const Ollama = typeof ollamaMod.Ollama === "function" ? ollamaMod.Ollama : ollamaMod.default;
    const sharp = require(require.resolve("sharp", { paths: depPaths }));

    const host = process.env.OLLAMA_BASE_URL;
    const client = new Ollama({ host });

    // num_predict mirrors the env default (8192) exactly like the server
    // would read it — WITHOUT OCR_NUM_CTX set and WITHOUT top_k: the
    // production-default PRE-FIX posture (D-16).
    const numPredict = Number(process.env.OCR_NUM_PREDICT || 8192);
    const numCtx = 4096; // the modelRegistry contextWindow posture being measured

    const fixtures = buildFixtures();

    /** @type {Array<{id: string, note: string, durationMs: number, tokensUsed: number, truncated: string, ttftMs: number, markdownLength: number}>} */
    const results = [];

    for (const fixture of fixtures) {
      const png = await sharp(fixture.svg).png().toBuffer();
      const base64 = png.toString("base64");
      const startedAt = Date.now();
      try {
        const stream = await client.chat({
          model: "glm-ocr:latest",
          messages: [
            { role: "system", content: "Text recognition:" },
            { role: "user", content: "Transcribe this document page as clean Markdown. Output ONLY the transcription." },
          ],
          images: [base64],
          stream: true,
          options: { temperature: 0, num_predict: numPredict, num_ctx: numCtx },
          keep_alive: "10m",
        });
        let content = "";
        let tokensUsed = 0;
        let truncated = false;
        let salvaged = false;
        let ttftMs = 0;
        let firstChunkAt = 0;
        try {
          for await (const chunk of stream) {
            const delta = chunk.message?.content ?? "";
            if (delta) {
              if (!firstChunkAt) {
                firstChunkAt = Date.now();
                ttftMs = firstChunkAt - startedAt;
              }
              content += delta;
            }
            if (chunk.done) {
              tokensUsed = chunk.eval_count ?? 0;
              if (chunk.done_reason === "length") truncated = true;
            }
          }
        } catch (streamErr) {
          // Salvage rule 260829-lkq parity: done-less stream with content =
          // degraded success, explicitly classified (Pitfall 8).
          const isDoneLess =
            streamErr instanceof Error &&
            streamErr.message === "Did not receive done or success response in stream.";
          if (isDoneLess && content.length > 0) {
            salvaged = true;
          } else {
            throw streamErr;
          }
        }
        const durationMs = Date.now() - startedAt;
        const classification = salvaged ? "salvaged" : truncated ? "truncated" : "clean";
        results.push({
          id: fixture.id,
          note: fixture.note,
          durationMs,
          tokensUsed,
          truncated: classification,
          ttftMs,
          markdownLength: content.length,
        });
        console.log(
          `${TOOL} ${fixture.id}: ${durationMs}ms, ${tokensUsed} tokens, ttft ${ttftMs}ms, class=${classification}, ${content.length} chars`,
        );
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        console.error(`${TOOL} ${fixture.id} FAILED: ${message}`);
        results.push({
          id: fixture.id,
          note: fixture.note,
          durationMs: -1,
          tokensUsed: -1,
          truncated: "failed",
          ttftMs: -1,
          markdownLength: 0,
        });
      }
    }

    // Write the rows into the marker-delimited block.
    const doc = readDoc();
    if (!doc) {
      console.error(`${TOOL} docs/OCR_RELIABILITY.md not found — run from the repo root`);
      process.exitCode = 1;
      return;
    }
    const rows = [
      `**Pre-fix baseline** — captured by \`scripts/ocr-baseline.cjs\` at ${new Date().toISOString()}`,
      `Posture: model \`glm-ocr:latest\`, chat endpoint, \`num_ctx 4096\` (registry posture), \`num_predict ${numPredict}\`, temperature 0, no \`top_k\` (pre-fix default).`,
      ``,
      `| Fixture | durationMs | tokensUsed | ttftMs | class | chars | note |`,
      `|---------|-----------:|-----------:|-------:|-------|------:|------|`,
      ...results.map(
        (r) =>
          `| ${r.id} | ${r.durationMs} | ${r.tokensUsed} | ${r.ttftMs} | ${r.truncated} | ${r.markdownLength} | ${r.note} |`,
      ),
      ``,
      `Environment: Ollama daemon at \`${host}\` — daemon/model/CPU details in the doc header.`,
    ].join("\n");
    fs.writeFileSync(DOC_PATH, writeBaselineBlock(doc, rows));
    console.log(`${TOOL} baseline rows written to docs/OCR_RELIABILITY.md`);

    // Clean up: remove the created optimized model? No — leave it; it is the
    // runbook artifact the operator wants. Nothing to clean (fixtures were
    // in-memory SVGs, never written to disk).
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.error(`${TOOL} failed: ${message}`);
    process.exitCode = 1;
  }
}

main();