/**
 * RUNBOOK (Phase 205-04, OCR-05 / D-13/D-14) — how to actually run this
 * suite locally:
 *
 *   # Skip branch (no daemon needed — must exit 0 via describe.skip):
 *   OLLAMA_BASE_URL= pnpm --filter server exec jest \
 *     --config jest.config.integration-nodb.js \
 *     --cacheDirectory .jest-cache/server-nodb \
 *     -- src/__tests__/ocrReliability.integration.test.ts
 *
 *   # Gated run (real daemon + pulled model — runs the pre/post comparison):
 *   OLLAMA_BASE_URL=http://localhost:11434 pnpm --filter server exec jest \
 *     --config jest.config.integration-nodb.js \
 *     --cacheDirectory .jest-cache/server-nodb \
 *     -- src/__tests__/ocrReliability.integration.test.ts
 *
 * - The integration-nodb config declares NO cacheDirectory of its own — the
 *   /tmp default fails in some environments, so the flag is REQUIRED on
 *   every invocation (do not drop it).
 * - No Postgres is needed: this suite needs only the ollama daemon, the
 *   committed fixtures and `helpers/setupEnv` (loaded as a setupFile by the
 *   nodb config; imported again here so the file is config-agnostic).
 * - The `OLLAMA_BASE_URL` skip-guard below (the `ollamaAvailable` const) is
 *   the correct no-model behavior: with the env var absent the suite skips
 *   — do NOT "fix" the `env.ts` OLLAMA_BASE_URL default
 *   (`http://ollama:11434`): it is compose-shaped by design and dead-DNS
 *   only for host-side processes, so pass the override at the command line.
 * - The model arm requires the model to be PULLED on the targeted instance
 *   (`ollama pull glm-ocr:latest`); the per-model availability probe below
 *   (`client.list()`) skips the fixture tests with an explicit reason when
 *   it is absent — never a fake fail, never a silent skip (204 D-05
 *   precedent). Operator opt-in: set `OCR_MODEL` to target another model
 *   (e.g. `glm-ocr-optimized:latest`) — the default stays `glm-ocr:latest`
 *   (Phase 205 D-12).
 * - Timeouts: vision is slow — PER_ARM_TIMEOUT_MS (300s) bounds one OCR
 *   call; each fixture test runs BOTH arms so its jest timeout is
 *   2 × arm + probe slack.
 *
 * What the suite does (per fixture, in the fixed order straight →
 * rotated-5deg → table → small-text):
 *  1. PRE arm  — jest-mocked `preprocessForOcr` passthrough (applied=false):
 *     the original fixture bytes reach `ocrPage` unmodified. The ONLY delta
 *     between the arms is preprocessing enabled vs disabled (OCR-05
 *     adjacency invariant — same fixture bytes, same model, same options).
 *  2. POST arm — the real 205-03 preprocessing chain runs (grayscale →
 *     resize ≤1024 → projection-profile deskew → JPEG q85). Before
 *     comparing markdown, the suite asserts the hook REALLY applied
 *     (`applied === true` for straight/rotated/table — suite-level ordering
 *     probe; small-text is exempt only if the estimator legitimately skips
 *     rotation, which the row records).
 *  3. Classify per Pitfall 8: clean (truncated falsy + non-empty),
 *     salvaged (truncated=true — the 260829-lkq done-less-stream rule
 *     counts as a DEGRADED SUCCESS, not a failure), failed (empty markdown
 *     or thrown).
 *  4. On the gated run, write the measured rows into the marker-delimited
 *     block in docs/OCR_RELIABILITY.md (idempotent replace). In CI the doc
 *     stays as-committed — never hand-write numbers there.
 */

